import os
import sys
import pandas as pd
import numpy as np
from datetime import timedelta
from pathlib import Path

try:
    from system.forecasting.implementations.n6_solar import N6SolarForecastEngine
    from system.optimization.implementations.gap19_highs_native import GAP19HighsNativeOptimizer
    from system.evaluation.n6_multi_origin_harness.adapters import _align_n6_bundle_od02
    from system.schemas.station_state import StationState
    from system.schemas.forecast_bundle import TimeseriesForecast
except ImportError as e:
    print(f"[FAIL] Import error: {e}")
    sys.exit(1)

def build_timeseries(values, unit="W"):
    return TimeseriesForecast(point=values, lower=values, upper=values, unit=unit)

def run_single_day_forensic():
    print("=" * 80)
    print("POLARIS — TRUE MACHINE LEARNING FORENSIC DEEP-DIVE (SINGLE DAY)")
    print("=" * 80)
    
    # 1. Target Origin: June 1st, 2024 (Midnight Sun / Polar Day)
    target_date = pd.to_datetime("2024-06-01T00:00:00Z")
    target_str = "2024-06-01T00:00:00Z"
    
    # 2. Load the Strict Causal 37-Feature Matrix
    matrix_path = "forecasting/stage7/stage8/stage8_1_station_tuning_research/candidate_k_baseline_conditioning/candidate_k_2024_clean_matrix.parquet"
    df_mat = pd.read_parquet(matrix_path)
    df_mat["forecast_start"] = pd.to_datetime(df_mat["forecast_start"], utc=True)
    
    # Extract strictly the 24 rows for our target day
    origin_rows = df_mat[df_mat["forecast_start"] == target_date].sort_values("horizon_hour").reset_index(drop=True)
    if len(origin_rows) != 24:
        print(f"[FAIL] Could not find exactly 24 hours of feature data for {target_str}")
        return
        
    # Synthesize missing feature if needed for pipeline compatibility
    if "elevation_x_transition_cloud" not in origin_rows.columns:
        is_trans = ((origin_rows["cloud_frac"] >= 0.2) & (origin_rows["cloud_frac"] < 0.6)).astype(np.float64)
        origin_rows["elevation_x_transition_cloud"] = origin_rows["solar_elevation"] * is_trans
        
    # DROP the future ground-truth to enforce strict causality
    features_df = origin_rows.drop(columns=["actual_SW_IN", "residual_target"], errors="ignore")
    
    # 3. Load Actual Ground Truth (for forensic comparison later)
    truth_df = pd.read_csv("data/POLARIS_v0_1_clearsky_decomposition.csv")
    truth_df['TIMESTAMP'] = pd.to_datetime(truth_df['TIMESTAMP'], utc=True)
    truth_df = truth_df.set_index('TIMESTAMP')
    
    actual_ghi = []
    for h in range(24):
        future_dt = target_date + timedelta(hours=h)
        try:
            actual_ghi.append(truth_df.loc[future_dt, 'actual_SW_IN'])
        except KeyError:
            actual_ghi.append(0.0)

    # 4. Instantiate Real Components
    n6_engine = N6SolarForecastEngine()
    optimizer = GAP19HighsNativeOptimizer()
    
    station_state = StationState(
        timestamp=target_str,
        battery_soc_pct=50.0,
        battery_energy_wh=100_000.0,
        diesel_running=False,
        diesel_hours_running=0.0,
        last_observed_solar_irradiance=0.0,
        last_observed_demand=30_000.0,
        last_observed_wind_generation=15_000.0,
        operating_mode="NORMAL"
    )
    
    # 5. EXECUTE REAL N6 INFERENCE
    print("\n[EXEC] Running N6 Gradient-Boosted Machine Learning Inference...")
    raw_bundle = n6_engine.predict(station_state, {"n6_feature_matrix": features_df})
    
    # 6. Apply OD-02-C Clear-Sky Ratio Alignment
    aligned_bundle = _align_n6_bundle_od02(raw_bundle)
    predicted_ghi = aligned_bundle.solar_irradiance.point
    
    # 7. Synthesize standard demand/wind for the solver step
    demand_w = [30_000.0 + 5_000.0 * np.sin((target_date.hour + h) * np.pi / 12.0) for h in range(24)]
    wind_w = [15_000.0 + 10_000.0 * np.sin(h * np.pi / 6.0) for h in range(24)]
    critical_w = [15_000.0] * 24
    
    aligned_bundle.demand = build_timeseries(demand_w, "W")
    aligned_bundle.wind_generation = build_timeseries(wind_w, "W")
    aligned_bundle.demand_critical = build_timeseries(critical_w, "W")
    
    config = {
        "operating_mode": "NORMAL",
        "battery": {"capacity_wh": 200_000.0, "min_soc_pct": 20.0, "max_soc_pct": 95.0},
        "diesel": {"min_power_w": 10_000.0, "max_power_w": 100_000.0},
        "terminal_reserve_model": "INITIAL_STATE",
        "optimizer": {"timestep_hours": 1.0}
    }
    
    # Add Conformal EBR targets if generated by N6
    if "ebr_target_wh" in aligned_bundle.metadata:
        config["ebr_target_wh"] = aligned_bundle.metadata["ebr_target_wh"]
        print(f"[INFO] Applied N6 Split-Conformal Emergency Battery Reserve (EBR).")

    # 8. EXECUTE GAP19 OPTIMIZER
    print("[EXEC] Running GAP19 MILP Optimizer...")
    plan = optimizer.optimize(forecast_bundle=aligned_bundle, station_state=station_state, config=config)

    # 9. PRINT FORENSIC REPORT
    print("\n" + "=" * 80)
    print(f"FORENSIC TRACE: {target_str}")
    print("=" * 80)
    print(f"{'Hour':>5} | {'N6 Forecast GHI':>16} | {'Actual GHI':>12} | {'Error':>8} | {'Diesel (kW)':>12} | {'Batt Net (kW)':>14}")
    print("-" * 80)
    
    for h in range(24):
        f_ghi = predicted_ghi[h]
        a_ghi = actual_ghi[h]
        err = f_ghi - a_ghi
        
        dsl = plan.diesel_power[h] / 1000.0 if hasattr(plan, 'diesel_power') else 0.0
        chg = plan.battery_charge[h] / 1000.0 if hasattr(plan, 'battery_charge') else 0.0
        dis = plan.battery_discharge[h] / 1000.0 if hasattr(plan, 'battery_discharge') else 0.0
        batt_net = dis - chg  # Positive = discharging, Negative = charging
        
        print(f"t+{h:02d} | {f_ghi:10.2f} W/m2 | {a_ghi:7.2f} W/m2 | {err:+6.1f} | {dsl:9.2f} kW | {batt_net:11.2f} kW")
        
    print("=" * 80)
    mae = sum(abs(p - a) for p, a in zip(predicted_ghi, actual_ghi)) / 24.0
    print(f"N6 Model Mean Absolute Error (MAE) for day: {mae:.2f} W/m2")
    print(f"Solver Status: {plan.constraint_status}")
    print("=" * 80)

if __name__ == "__main__":
    run_single_day_forensic()
